import { expect, test } from "bun:test";
import { failing, gitmodules, load, problems, relativeUrl, render, type Registry, type Row } from "./stack.ts";

const base = (upstream: Registry["upstream"], reference: Registry["reference"] = []): Registry => ({
  product: { name: "aysh", owner: "dev", forks: "labs", cli: "aysh", license: "Apache-2.0" },
  hosts: {},
  upstream,
  reference,
});

test("the repository's own registry is valid", async () => {
  const reg = await load();
  expect(problems(reg)).toEqual([]);
  expect(reg.upstream.length).toBeGreaterThan(0);
});

test("a fork that reaches others through relative paths is vendored beside them", () => {
  const trio = (rubash: string | undefined) =>
    base([
      { name: "niubash", upstream: "unixwin/niubash", role: "host", path: "third_party/unixwin/niubash", mode: "source", siblings: ["rubash", "ruline"] },
      { name: "rubash", upstream: "unixwin/rubash", role: "engine", ...(rubash ? { path: rubash, mode: "source" as const } : {}) },
      { name: "ruline", upstream: "unixwin/ruline", role: "editor", path: "third_party/unixwin/ruline", mode: "source" },
    ]);
  expect(problems(trio("third_party/unixwin/rubash"))).toEqual([]);
  expect(problems(trio("third_party/rubash"))).toEqual(["niubash: sibling rubash is not vendored at third_party/unixwin/rubash"]);
  expect(problems(trio(undefined))).toEqual(["niubash: sibling rubash is not vendored at third_party/unixwin/rubash"]);
});

test("siblings are not required while the fork itself is only tracked", () => {
  expect(problems(base([{ name: "niubash", upstream: "unixwin/niubash", role: "host", siblings: ["rubash"] }, { name: "rubash", upstream: "unixwin/rubash", role: "engine" }]))).toEqual([]);
});

test("problems reports duplicates, bad slugs, bad paths and modes", () => {
  const reg = base(
    [
      { name: "a", upstream: "o/a", role: "x" },
      { name: "a", upstream: "o/a", role: "x" },
      { name: "b", upstream: "not a slug", role: "x" },
      { name: "c", upstream: "o/c", role: " " },
      { name: "d", upstream: "o/d", role: "x", mode: "source" },
      { name: "e", upstream: "o/e", role: "x", path: "third_party/e" },
      { name: "f", upstream: "o/f", role: "x", path: "../f", mode: "source" },
      { name: "g", upstream: "o/g", role: "x", path: "C:/g", mode: "source" },
      { name: "h", upstream: "o/h", role: "x", path: "third_party/e", mode: "corpus" },
      { name: "m", upstream: "o/m", role: "x", mirror: true },
    ],
    [{ upstream: "nope", role: "" }],
  );
  const got = problems(reg);
  for (const want of [
    "a: listed twice",
    'b: upstream "not a slug" is not owner/repo',
    "c: no role",
    "d: mode without path",
    "e: a vendored fork has mode source or corpus",
    'f: path "../f" is not a relative POSIX path inside the repository',
    'g: path "C:/g" is not a relative POSIX path inside the repository',
    "h: path third_party/e used twice",
    "m: a mirror names its source by https URL",
    "m: a mirror names its branch",
    'reference "nope" is not owner/repo',
    "reference nope: no role",
  ]) {
    expect(got).toContain(want);
  }
});

test("fork URLs are relative to this repository's remote", () => {
  expect(relativeUrl("dev", "labs", "rubash")).toBe("../../labs/rubash.git");
  expect(relativeUrl("labs", "labs", "rubash")).toBe("../rubash.git");
});

test("gitmodules lists only vendored forks; a corpus is never checked out by default", () => {
  const reg = base([
    { name: "rubash", upstream: "unixwin/rubash", role: "engine", path: "third_party/unixwin/rubash", mode: "source" },
    { name: "rio", upstream: "raphamorim/rio", role: "vt" },
    { name: "bash", upstream: "https://example.org/bash.git", branch: "master", mirror: true, role: "corpus", path: "third_party/corpus/bash", mode: "corpus" },
  ]);
  const text = gitmodules(reg, new Map([["rubash", "master"], ["bash", "master"]]));
  expect(text).toBe(
    [
      "# Generated by tools/stack.ts from aysh.toml. Do not edit.",
      '[submodule "third_party/unixwin/rubash"]',
      "\tpath = third_party/unixwin/rubash",
      "\turl = ../../labs/rubash.git",
      "\tbranch = master",
      "\tshallow = true",
      '[submodule "third_party/corpus/bash"]',
      "\tpath = third_party/corpus/bash",
      "\turl = ../../labs/bash.git",
      "\tbranch = master",
      "\tshallow = true",
      "\tupdate = none",
      "",
    ].join("\n"),
  );
  expect(() => gitmodules(reg, new Map())).toThrow("rubash: no branch resolved");
});

test("status fails on a fork behind its upstream and on a gitlink off its fork's tip", () => {
  const tip = "a".repeat(40);
  const rows: Row[] = [
    { name: "ok", branch: "main", ahead: 3, behind: 0, tip, gitlink: tip },
    { name: "tracked", branch: "main", ahead: 0, behind: 0, tip, gitlink: null },
    { name: "mirror", branch: "master", ahead: null, behind: null, tip, gitlink: null },
    { name: "late", branch: "main", ahead: 0, behind: 7, tip, gitlink: null },
    { name: "stale", branch: "main", ahead: 0, behind: 0, tip, gitlink: "b".repeat(40) },
    { name: "missing", branch: "main", ahead: 0, behind: 0, tip, gitlink: "" },
  ];
  expect(failing(rows)).toEqual([
    "late: 7 behind its upstream",
    "stale: gitlink bbbbbbbbbbbb is not the fork tip aaaaaaaaaaaa",
    "missing: not vendored yet (run the modules step)",
  ]);
  expect(failing(rows.slice(0, 3))).toEqual([]);
  const lines = render(rows).split("\n");
  expect(lines[0]).toBe("fork     branch  ahead  behind  tip           gitlink");
  expect(lines[3]).toBe("mirror   master  -      -       aaaaaaaaaaaa  -");
});
