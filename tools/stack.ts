#!/usr/bin/env bun
/**
 * Applies the [[upstream]] table of aysh.toml: the forks, `.gitmodules`, the gitlinks.
 *
 *   bun tools/stack.ts status    # every fork against its upstream (ahead, behind) and every gitlink against its fork
 *   bun tools/stack.ts forks     # create missing forks, fast-forward the ones that have no commits of their own
 *   bun tools/stack.ts modules   # write .gitmodules (relative URLs) and add missing submodules
 *   bun tools/stack.ts pin       # move every gitlink to the tip of its fork's branch
 *
 * A fork with commits of its own is never fast-forwarded: it is reported as diverged and merged by hand on the
 * build host. `status` exits 1 when a fork is behind its upstream or a gitlink is not at its fork's tip.
 */

import { join, resolve } from "node:path";

export type Mode = "source" | "corpus";

export interface Upstream {
  name: string;
  upstream: string;
  branch?: string;
  base?: string;
  path?: string;
  mode?: Mode;
  mirror?: boolean;
  siblings?: string[];
  role: string;
}

export interface Reference {
  upstream: string;
  role: string;
}

export interface Registry {
  product: { name: string; owner: string; forks: string; cli: string; license: string };
  hosts: Record<string, string>;
  paths?: Record<string, Record<string, string>>;
  upstream: Upstream[];
  reference?: Reference[];
}

const MODES: readonly Mode[] = ["source", "corpus"];
const SLUG = /^[A-Za-z0-9._-]+\/[A-Za-z0-9._-]+$/;

/** Every problem of a registry, as messages. Empty when the registry is valid. */
export function problems(reg: Registry): string[] {
  const out: string[] = [];
  const names = new Set<string>();
  const paths = new Set<string>();
  for (const u of reg.upstream) {
    if (names.has(u.name)) out.push(`${u.name}: listed twice`);
    names.add(u.name);
    if (!u.role?.trim()) out.push(`${u.name}: no role`);
    if (u.mirror) {
      if (!/^https:\/\//.test(u.upstream)) out.push(`${u.name}: a mirror names its source by https URL`);
      if (!u.branch) out.push(`${u.name}: a mirror names its branch`);
    } else if (!SLUG.test(u.upstream)) {
      out.push(`${u.name}: upstream "${u.upstream}" is not owner/repo`);
    }
    if (u.path === undefined) {
      if (u.mode !== undefined) out.push(`${u.name}: mode without path`);
      continue;
    }
    if (!u.mode || !MODES.includes(u.mode)) out.push(`${u.name}: a vendored fork has mode ${MODES.join(" or ")}`);
    if (u.path.startsWith("/") || u.path.includes("\\") || u.path.includes("..") || /^[A-Za-z]:/.test(u.path)) {
      out.push(`${u.name}: path "${u.path}" is not a relative POSIX path inside the repository`);
    }
    if (paths.has(u.path)) out.push(`${u.name}: path ${u.path} used twice`);
    paths.add(u.path);
    const parent = u.path.replace(/\/?[^/]+$/, "");
    for (const name of u.siblings ?? []) {
      const want = parent ? `${parent}/${name}` : name;
      if (reg.upstream.find(o => o.name === name)?.path !== want) out.push(`${u.name}: sibling ${name} is not vendored at ${want}`);
    }
  }
  for (const r of reg.reference ?? []) {
    if (!SLUG.test(r.upstream)) out.push(`reference "${r.upstream}" is not owner/repo`);
    if (!r.role?.trim()) out.push(`reference ${r.upstream}: no role`);
  }
  return out;
}

/** URL of a fork relative to this repository's own remote, so a fork of this repository finds its own forks. */
export function relativeUrl(owner: string, forks: string, name: string): string {
  return owner === forks ? `../${name}.git` : `../../${forks}/${name}.git`;
}

/** `.gitmodules` for the vendored forks. `branches` maps a fork name to the branch it follows. */
export function gitmodules(reg: Registry, branches: ReadonlyMap<string, string>): string {
  const lines = ["# Generated by tools/stack.ts from aysh.toml. Do not edit."];
  for (const u of reg.upstream) {
    if (!u.path) continue;
    const branch = branches.get(u.name);
    if (!branch) throw new Error(`${u.name}: no branch resolved`);
    lines.push(
      `[submodule "${u.path}"]`,
      `\tpath = ${u.path}`,
      `\turl = ${relativeUrl(reg.product.owner, reg.product.forks, u.name)}`,
      `\tbranch = ${branch}`,
      "\tshallow = true",
    );
    if (u.mode === "corpus") lines.push("\tupdate = none");
  }
  return `${lines.join("\n")}\n`;
}

/** One line of `status`. `behind` > 0 or a gitlink off its tip makes the status fail. */
export interface Row {
  name: string;
  branch: string;
  ahead: number | null;
  behind: number | null;
  tip: string;
  gitlink: string | null;
}

export function failing(rows: readonly Row[]): string[] {
  const out: string[] = [];
  for (const r of rows) {
    if (r.behind !== null && r.behind > 0) out.push(`${r.name}: ${r.behind} behind its upstream`);
    if (r.gitlink === "") out.push(`${r.name}: not vendored yet (run the modules step)`);
    else if (r.gitlink !== null && r.gitlink !== r.tip) out.push(`${r.name}: gitlink ${r.gitlink.slice(0, 12)} is not the fork tip ${r.tip.slice(0, 12)}`);
  }
  return out;
}

export function render(rows: readonly Row[]): string {
  const cell = (n: number | null) => (n === null ? "-" : String(n));
  const table = rows.map(r => [r.name, r.branch, cell(r.ahead), cell(r.behind), r.tip.slice(0, 12), r.gitlink === null ? "-" : r.gitlink.slice(0, 12) || "missing"]);
  const head = ["fork", "branch", "ahead", "behind", "tip", "gitlink"];
  const width = head.map((h, i) => Math.max(h.length, ...table.map(row => row[i]!.length)));
  return [head, ...table].map(row => row.map((c, i) => c.padEnd(width[i]!)).join("  ").trimEnd()).join("\n");
}

// ---------------------------------------------------------------------------------------------------------------------

const root = resolve(import.meta.dirname, "..");

export async function load(file = join(root, "aysh.toml")): Promise<Registry> {
  const reg = Bun.TOML.parse(await Bun.file(file).text()) as unknown as Registry;
  const bad = problems(reg);
  if (bad.length) throw new Error(`aysh.toml:\n  ${bad.join("\n  ")}`);
  return reg;
}

async function sh(cmd: string[], cwd = root, ok = false): Promise<string> {
  const p = Bun.spawn(cmd, { cwd, stdin: "ignore", stdout: "pipe", stderr: "pipe" });
  const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]);
  if (code !== 0 && !ok) throw new Error(`${cmd.join(" ")}: ${err.trim() || `exit ${code}`}`);
  return code === 0 ? out.trim() : "";
}

async function branchOf(u: Upstream): Promise<string> {
  return u.branch ?? (await sh(["gh", "api", `repos/${u.upstream}`, "--jq", ".default_branch"]));
}

function forkUrl(reg: Registry, u: Upstream): string {
  return `https://github.com/${reg.product.forks}/${u.name}.git`;
}

async function tipOf(reg: Registry, u: Upstream, branch: string): Promise<string> {
  const sha = (await sh(["git", "ls-remote", forkUrl(reg, u), `refs/heads/${branch}`])).split(/\s/)[0];
  if (!sha) throw new Error(`${reg.product.forks}/${u.name}: no branch ${branch}`);
  return sha;
}

async function rows(reg: Registry): Promise<Row[]> {
  const links = new Map<string, string>();
  for (const line of (await sh(["git", "ls-files", "-s"], root, true)).split("\n")) {
    const m = line.match(/^160000 ([0-9a-f]{40}) \d\t(.+)$/);
    if (m) links.set(m[2]!, m[1]!);
  }
  return Promise.all(
    reg.upstream.map(async u => {
      const branch = await branchOf(u);
      const tip = await tipOf(reg, u, branch);
      let ahead: number | null = null;
      let behind: number | null = null;
      if (!u.mirror) {
        const cmp = await sh(["gh", "api", `repos/${u.upstream}/compare/${u.base ?? branch}...${reg.product.forks}:${u.name}:${branch}`, "--jq", "[.ahead_by, .behind_by] | @tsv"]);
        [ahead, behind] = cmp.split("\t").map(Number) as [number, number];
      }
      return { name: u.name, branch, ahead, behind, tip, gitlink: u.path ? (links.get(u.path) ?? "") : null };
    }),
  );
}

async function status(reg: Registry): Promise<void> {
  const all = await rows(reg);
  console.log(render(all));
  const bad = failing(all);
  if (bad.length) {
    console.error(`\n${bad.join("\n")}`);
    process.exit(1);
  }
}

async function forks(reg: Registry): Promise<void> {
  await Promise.all(
    reg.upstream
      .filter(u => !u.mirror)
      .map(async u => {
        const slug = `${reg.product.forks}/${u.name}`;
        if (!(await sh(["gh", "api", `repos/${slug}`, "--jq", ".full_name"], root, true))) {
          await sh(["gh", "repo", "fork", u.upstream, "--org", reg.product.forks, "--fork-name", u.name, "--clone=false", "--default-branch-only"]);
          console.log(`${slug}: forked from ${u.upstream}`);
        }
        const branch = await branchOf(u);
        const cmp = await sh(["gh", "api", `repos/${u.upstream}/compare/${u.base ?? branch}...${reg.product.forks}:${u.name}:${branch}`, "--jq", "[.ahead_by, .behind_by] | @tsv"]);
        const [ahead, behind] = cmp.split("\t").map(Number) as [number, number];
        if (behind === 0) console.log(`${slug}: up to date`);
        else if (ahead > 0 || u.base) console.log(`${slug}: diverged (${ahead} ahead, ${behind} behind); merge ${u.upstream} ${u.base ?? branch} on the build host`);
        else {
          await sh(["gh", "repo", "sync", slug, "--source", u.upstream, "--branch", branch]);
          console.log(`${slug}: fast-forwarded ${behind} commits`);
        }
      }),
  );
}

async function modules(reg: Registry): Promise<void> {
  const vendored = reg.upstream.filter(u => u.path);
  const branches = new Map(await Promise.all(vendored.map(async u => [u.name, await branchOf(u)] as const)));
  await Bun.write(join(root, ".gitmodules"), gitmodules(reg, branches));
  await sh(["git", "add", ".gitmodules"]);
  const staged = new Set((await sh(["git", "ls-files", "-s"])).split("\n").map(l => l.split("\t")[1]));
  // The network runs in parallel; the index has one writer, so its updates run one after another.
  const fetched = await Promise.all(
    vendored
      .filter(u => !staged.has(u.path!))
      .map(async u => {
        const branch = branches.get(u.name)!;
        if (u.mode === "corpus") return { u, sha: await tipOf(reg, u, branch) };
        await sh(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "-b", branch, forkUrl(reg, u), u.path!]);
        return { u, sha: "" };
      }),
  );
  for (const { u, sha } of fetched) {
    if (sha) await sh(["git", "update-index", "--add", "--cacheinfo", `160000,${sha},${u.path}`]);
    else {
      await sh(["git", "add", "--", u.path!]);
      await sh(["git", "submodule", "absorbgitdirs", "--", u.path!], root, true);
    }
    console.log(`added ${u.path}`);
  }
  await sh(["git", "submodule", "init"], root, true);
}

async function pin(reg: Registry): Promise<void> {
  const moved = await Promise.all(
    reg.upstream
      .filter(u => u.path)
      .map(async u => {
        const branch = await branchOf(u);
        const dir = join(root, u.path!);
        if (u.mode === "corpus" || !(await Bun.file(join(dir, ".git")).exists())) return { u, sha: await tipOf(reg, u, branch) };
        await sh(["git", "fetch", "-q", "--depth", "1", "origin", branch], dir);
        await sh(["git", "checkout", "-q", "--detach", "FETCH_HEAD"], dir);
        return { u, sha: await sh(["git", "rev-parse", "HEAD"], dir) };
      }),
  );
  for (const { u, sha } of moved) {
    await sh(["git", "update-index", "--add", "--cacheinfo", `160000,${sha},${u.path}`]);
    console.log(`${u.path} ${sha.slice(0, 12)}`);
  }
}

if (import.meta.main) {
  const steps: Record<string, (reg: Registry) => Promise<void>> = { status, forks, modules, pin };
  const step = process.argv[2] ?? "status";
  const run = steps[step];
  if (!run) {
    console.error(`unknown step ${step}; one of ${Object.keys(steps).join(", ")}`);
    process.exit(2);
  }
  await run(await load());
}
